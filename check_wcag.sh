#!/bin/bash
# ==============================================================================
# WCAG アクセシビリティ自動監査 ＆ レポート自動表示スクリプト
# ==============================================================================

# エラーが起きたらスクリプトを停止する
set -e

# スクリプトが存在するディレクトリ（wcagフォルダ）に移動
cd "$(dirname "$0")"

echo "==================================================="
echo "🔨 1. コンテナ環境のビルド（最新化）を確認しています..."
echo "==================================================="
docker compose build

echo ""
echo "==================================================="
echo "🚀 2. アクセシビリティ監査を実行しています..."
echo "==================================================="
docker compose run --rm pa11y

echo ""
echo "==================================================="
echo "🌐 3. 最新のレポートをブラウザで開きます..."
echo "==================================================="
# reportsディレクトリ内で、過去1分以内に作成された「一覧ページ（summary_*.html）」を探す
SUMMARY_REPORT=$(find reports -name "summary_*.html" -mmin -1 | head -n 1)

if [ -n "$SUMMARY_REPORT" ]; then
    # 一覧ページがあればそれを開く（複数ファイルの場合）
    open "$SUMMARY_REPORT"
    echo "✅ ブラウザで一覧ページ（${SUMMARY_REPORT}）を開きました！"
else
    # 一覧ページがない場合は、単一のレポートファイルを開く
    SINGLE_REPORT=$(find reports -name "report_*.html" -mmin -1 | head -n 1)
    if [ -n "$SINGLE_REPORT" ]; then
        open "$SINGLE_REPORT"
        echo "✅ ブラウザでレポート（${SINGLE_REPORT}）を開きました！"
    else
        echo "⚠️ レポートファイルが見つかりませんでした。"
    fi
fi
